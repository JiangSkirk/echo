def _validate_ack_semantics(envelope: dict[str, Any]) -> None:
    """Check ``ok``/``code`` consistency and success payloads on acks."""

    message_type = envelope["type"]
    if not message_type.endswith("_ack"):
        return
    ok = envelope.get("ok", True)
    code = envelope.get("code")
    if not ok:
        if code is None:
            raise ProtocolError("failed acks require a 'code'")
        if code not in ERROR_CODES:
            raise ProtocolError(f"unknown error code {code!r}")
        return
    if code is not None:
        raise ProtocolError("'code' must be absent on successful acks")
    if message_type == "hello_ack" and "server_nonce" not in envelope:
        raise ProtocolError("successful hello_ack requires 'server_nonce'")
    if message_type == "issue_ack":
        for field in ("lease", "context_signature", "receipt_id"):
            if field not in envelope:
                raise ProtocolError(f"successful issue_ack requires {field!r}")
        validate_lease_dict(envelope["lease"])
    if message_type == "consume_ack":
        verdict = envelope.get("verdict")
        if verdict not in VERDICTS:
            raise ProtocolError("consume_ack verdict must be a known verdict")


def _validate_revoke_semantics(envelope: dict[str, Any]) -> None:
    """Check op/field consistency on revoke requests and revoke_ack replies."""

    message_type = envelope["type"]
    if message_type == "revoke":
        op = envelope.get("op") or _infer_revoke_op(envelope)
        if op not in REVOKE_OPS:
            raise ProtocolError(f"unknown revoke op {op!r}")
        if op == "lease" and not envelope.get("lease_id"):
            raise ProtocolError("revoke op 'lease' requires 'lease_id'")
        if op == "session" and not (envelope.get("owner_key_hash") and envelope.get("session_id")):
            raise ProtocolError("revoke op 'session' requires owner and session")
        if op == "active_sessions" and not envelope.get("owner_key_hash"):
            raise ProtocolError("revoke op 'active_sessions' requires 'owner_key_hash'")
        if op == "is_revoked" and not envelope.get("lease_id"):
            raise ProtocolError("revoke op 'is_revoked' requires 'lease_id'")
    elif message_type == "revoke_ack":
        if envelope.get("ok", True):
            has_result = any(key in envelope for key in ("revoked", "sessions", "is_revoked"))
            if not has_result:
                raise ProtocolError("successful revoke_ack requires a result field")


def _validate_stageb_semantics(envelope: dict[str, Any]) -> None:
    """Op/field consistency for Stage B messages (deep sub-schemas live in
    ``js.orin.intent`` / ``js.orin.handles`` / ``js.orin.draft``)."""

    message_type = envelope["type"]
    if message_type == "intent":
        op = envelope.get("op")
        if op not in INTENT_OPS:
            raise ProtocolError(f"unknown intent op {op!r}")
        intent = envelope.get("intent")
        grant = envelope.get("grant")
        if op in {"grant_export", "grant_exact"}:
            if not isinstance(grant, dict):
                raise ProtocolError(f"{op} requires a 'grant' object")
            if envelope.get("task_id") is None:
                raise ProtocolError(f"{op} requires 'task_id'")
            if op == "grant_exact" and not str(envelope["task_id"]).startswith("task:"):
                raise ProtocolError("grant_exact requires a bounded 'task:' id")
            if intent is not None:
                raise ProtocolError(f"{op} carries fields, not an 'intent' object")
            if op == "grant_exact" and envelope.get("session_id") is not None:
                raise ProtocolError("grant_exact must not carry 'session_id'")
        elif op in ("register", "admin_unfreeze"):
            if not isinstance(intent, dict):
                raise ProtocolError(f"intent op {op!r} requires an 'intent' object")
            if op == "register" and grant is not None:
                if not isinstance(grant, dict):
                    raise ProtocolError("intent register 'grant' must be an object")
                session_id = envelope.get("session_id")
                if not isinstance(session_id, str) or not session_id:
                    raise ProtocolError("intent register with 'grant' requires 'session_id'")
            elif grant is not None:
                raise ProtocolError(f"intent op {op!r} must not carry a 'grant' object")
        elif intent is not None:
            raise ProtocolError(f"intent op {op!r} must not carry an 'intent' object")
        elif grant is not None:
            raise ProtocolError(f"intent op {op!r} must not carry a 'grant' object")
    elif message_type == "handle":
        op = envelope.get("op")
        if op not in HANDLE_OPS:
            raise ProtocolError(f"unknown handle op {op!r}")
        if op == "issue" and not isinstance(envelope.get("spec"), dict):
            raise ProtocolError("handle op 'issue' requires a 'spec' object")
        if op == "resolve" and not envelope.get("handle") and not envelope.get("kind"):
            raise ProtocolError("handle op 'resolve' requires 'handle' or 'kind'")
    elif message_type == "handle_ack":
        if envelope.get("ok", True):
            has_result = any(key in envelope for key in ("handle", "candidates"))
            if not has_result:
                raise ProtocolError("successful handle_ack requires 'handle' or 'candidates'")
    elif message_type == "draft_ack":
        if envelope.get("ok", True):
            verdict = envelope.get("verdict")
            if verdict not in GATE_VERDICTS:
                raise ProtocolError("draft_ack verdict must be a Gate Kernel class")
            missing = envelope.get("missing", [])
            if not isinstance(missing, list) or any(not isinstance(m, str) for m in missing):
                raise ProtocolError("draft_ack 'missing' must be a list of strings")
    elif message_type == "reconcile_ack":
        if envelope.get("ok", True) and envelope.get("state") not in RECONCILE_STATES:
            raise ProtocolError("successful reconcile_ack requires a known 'state'")


def _infer_revoke_op(envelope: dict[str, Any]) -> str:
    if envelope.get("lease_id"):
        return "lease"
    if envelope.get("owner_key_hash") and envelope.get("session_id"):
        return "session"
    return ""


def canonical_json(value: Any) -> str:
    """Deterministic JSON used as the MAC pre-image (sorted keys, no spaces)."""

    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def compute_mac(session_key: bytes, envelope: dict[str, Any]) -> str:
    """HMAC-SHA256 over the canonical JSON of the envelope without ``mac``."""

    payload = {key: value for key, value in envelope.items() if key != "mac"}
    digest = hmac.new(session_key, canonical_json(payload).encode("utf-8"), hashlib.sha256)
    return MAC_PREFIX + digest.hexdigest()


def verify_mac(session_key: bytes, envelope: dict[str, Any]) -> bool:
    """Constant-time check of the envelope ``mac`` field."""

    presented = envelope.get("mac")
    if not isinstance(presented, str) or not presented.startswith(MAC_PREFIX):
        return False
    expected = compute_mac(session_key, envelope)
    return hmac.compare_digest(presented, expected)


def _check_depth(value: Any, depth: int = 0) -> bool:
    if depth > MAX_JSON_DEPTH:
        return False
    if isinstance(value, dict):
        return all(_check_depth(item, depth + 1) for item in value.values())
    if isinstance(value, list):
        return all(_check_depth(item, depth + 1) for item in value)
    return True


def _validate_fields(
    envelope: dict[str, Any],
    specs: tuple[FieldSpec, ...],
    *,
    reject_unknown: bool,
) -> None:
    known = {spec.name for spec in specs}
    if reject_unknown:
        for key in envelope:
            if key not in known and key not in {"seq", "nonce", "mac"}:
                raise ProtocolError(f"unknown field {key!r}")
    for spec in specs:
        if spec.name not in envelope:
            if spec.optional:
                continue
            raise ProtocolError(f"missing field {spec.name!r}")
        value = envelope[spec.name]
        kind_ok = isinstance(value, spec.kinds)
        if kind_ok and isinstance(value, bool) and bool not in spec.kinds:
            kind_ok = False
        if not kind_ok:
            raise ProtocolError(f"field {spec.name!r} has wrong type")
        if isinstance(value, str) and len(value) > spec.max_len:
            raise ProtocolError(f"field {spec.name!r} exceeds length cap")
        if (
            isinstance(value, int)
            and not isinstance(value, bool)
            and not spec.lo <= value <= spec.hi
        ):
            raise ProtocolError(f"field {spec.name!r} out of range")


def parse_frame(data: bytes) -> dict[str, Any]:
    """Decode one frame payload with strict envelope + schema validation.

    ``data`` must be the JSON payload (after the 4-byte length prefix was
    consumed). Raises :class:`ProtocolError` on any violation.
    """

    if len(data) > MAX_FRAME_BYTES:
        raise ProtocolError("frame exceeds 64KiB")
    try:
        envelope = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ProtocolError("frame is not valid UTF-8 JSON") from exc
    if not isinstance(envelope, dict):
        raise ProtocolError("frame payload must be a JSON object")
    if not _check_depth(envelope):
        raise ProtocolError("frame JSON depth exceeds 16")

    _validate_fields(envelope, ENVELOPE_FIELDS, reject_unknown=False)
    message_type = envelope["type"]
    if message_type not in MESSAGE_TYPES:
        raise ProtocolError(f"unknown message type {message_type!r}")
    _validate_fields(envelope, _SCHEMA[message_type], reject_unknown=True)
    _validate_ack_semantics(envelope)
    _validate_revoke_semantics(envelope)
    _validate_stageb_semantics(envelope)
    if message_type == "consume":
        validate_consume_request(envelope)
    elif message_type == "issue":
        lease_params = envelope.get("lease")
        if not isinstance(lease_params, dict):
            raise ProtocolError("issue requires a 'lease' parameter object")
        context_fields = envelope.get("context")
        if context_fields is not None and not isinstance(context_fields, dict):
            raise ProtocolError("issue 'context' must be an object")
        validate_issue_request(lease_params, context_fields)

    nonce = envelope["nonce"]
    if not _NONCE_RE.fullmatch(nonce):
        raise ProtocolError("nonce must be 16-64 urlsafe characters")
    mac = envelope.get("mac")
    if message_type in UNAUTHENTICATED_TYPES:
        if mac is not None:
            raise ProtocolError("handshake messages must not carry a mac")
    elif mac is None:
        raise ProtocolError("message requires a mac")
    return envelope


def encode_frame(envelope: dict[str, Any]) -> bytes:
    """Serialize an envelope to a length-prefixed frame (ready to send)."""

    payload = json.dumps(envelope, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    if len(payload) > MAX_FRAME_BYTES:
        raise ProtocolError("frame exceeds 64KiB")
    return len(payload).to_bytes(4, "big") + payload


def make_envelope(
    message_type: str,
    *,
    seq: int,
    nonce: str,
    session_key: bytes | None,
    **fields: Any,
) -> dict[str, Any]:
    """Build a valid envelope, attaching the MAC when authenticated."""

    envelope: dict[str, Any] = {
        "v": PROTOCOL_VERSION,
        "type": message_type,
        "seq": seq,
        "nonce": nonce,
        **fields,
    }
    if session_key is not None:
        if message_type in UNAUTHENTICATED_TYPES:
            raise ProtocolError("handshake messages must not carry a mac")
        envelope["mac"] = compute_mac(session_key, envelope)
    parse_frame(canonical_json(envelope).encode("utf-8"))
    return envelope


def validate_lease_dict(lease: dict[str, Any]) -> None:
    """Strict shape check for serialized CapabilityLease payloads."""

    required_strings = (
        "lease_id",
        "owner_key_hash",
        "run_id",
        "tool_name",
        "args_schema",
        "resource_scope",
        "nonce",
    )
    for key in required_strings:
        value = lease.get(key)
        if not isinstance(value, str) or not value:
            raise ProtocolError(f"lease field {key!r} must be a non-empty string")
        if len(value) > 256:
            raise ProtocolError(f"lease field {key!r} exceeds length cap")
    mac = lease.get("mac")
    if not isinstance(mac, str) or not _LEASE_MAC_RE.fullmatch(mac):
        raise ProtocolError("lease mac must be 64 lowercase hex chars")
    for key in ("product_id", "session_id"):
        value = lease.get(key, "")
        if not isinstance(value, str) or len(value) > 256:
            raise ProtocolError(f"lease field {key!r} must be a bounded string")
    for key in ("fs_roots", "network_hosts"):
        value = lease.get(key, ())
        if not isinstance(value, (list, tuple)) or any(
            not isinstance(item, str) or len(item) > 4096 for item in value
        ):
            raise ProtocolError(f"lease field {key!r} must be a list of bounded strings")
    network_policy = lease.get("network_policy", "deny")
    if network_policy not in ("allow", "deny"):
        raise ProtocolError("lease network_policy must be allow|deny")
    for key in ("max_bytes", "max_duration_ms", "expires_at"):
        value = lease.get(key)
        if not isinstance(value, int) or isinstance(value, bool) or not 0 <= value <= MAX_SEQ:
            raise ProtocolError(f"lease field {key!r} must be a u64 integer")
    max_invocations = lease.get("max_invocations")
    if (
        not isinstance(max_invocations, int)
        or isinstance(max_invocations, bool)
        or not 1 <= max_invocations <= (1 << 32)
    ):
        raise ProtocolError("lease max_invocations must be a positive u32")
    parent = lease.get("parent_lease_id")
    if parent is not None and (not isinstance(parent, str) or len(parent) > 64):
        raise ProtocolError("lease parent_lease_id must be a bounded string")


def validate_issue_request(
    lease: dict[str, Any],
    context: dict[str, Any] | None,
) -> None:
    """Validate an issue request payload (params, not yet a lease)."""

    required_strings = (
        "owner_key_hash",
        "run_id",
        "tool_name",
        "args_schema",
        "resource_scope",
    )
    for key in required_strings:
        value = lease.get(key)
        if not isinstance(value, str) or not value:
            raise ProtocolError(f"issue field {key!r} must be a non-empty string")
    for key in ("fs_roots", "network_hosts"):
        value = lease.get(key)
        if value is None:
            continue
        if not isinstance(value, (list, tuple)) or any(not isinstance(item, str) for item in value):
            raise ProtocolError(f"issue field {key!r} must be a list of strings")
    network_policy = lease.get("network_policy", "deny")
    if network_policy not in ("allow", "deny"):
        raise ProtocolError("issue network_policy must be allow|deny")
    for key in ("max_bytes", "max_duration_ms", "ttl_ms"):
        value = lease.get(key)
        if not isinstance(value, int) or isinstance(value, bool) or not 0 <= value <= MAX_SEQ:
            raise ProtocolError(f"issue field {key!r} must be a u64 integer")
    max_invocations = lease.get("max_invocations", 1)
    if (
        not isinstance(max_invocations, int)
        or isinstance(max_invocations, bool)
        or max_invocations < 1
    ):
        raise ProtocolError("issue max_invocations must be >= 1")
    if context is not None:
        profile = context.get("profile", "")
        if not isinstance(profile, str) or len(profile) > 256:
            raise ProtocolError("issue context profile must be a bounded string")


def validate_consume_request(envelope: dict[str, Any]) -> None:
    """Mode-aware structural validation for a consume request.

    The daemon always uses its own clock; requests carry no time field by
    design (client time is untrusted).
    """

    mode = envelope.get("mode")
    if mode not in CONSUME_MODES:
        raise ProtocolError(f"unknown consume mode {mode!r}")
    if mode == "scan":
        scan_text = envelope.get("scan_text")
        session_id = envelope.get("session_id")
        if not isinstance(scan_text, str) or not scan_text:
            raise ProtocolError("consume mode 'scan' requires non-empty scan_text")
        if not isinstance(session_id, str) or not session_id:
            raise ProtocolError("consume mode 'scan' requires session_id")
        return
    if mode == "context":
        if "context" not in envelope:
            raise ProtocolError("consume mode 'context' requires 'context'")
        return
    if mode == "cell":
        payload = envelope.get("payload")
        if not isinstance(payload, dict):
            raise ProtocolError("consume mode 'cell' requires a 'payload' object")
        if set(payload) == {"draft_id"}:
            draft_id = payload.get("draft_id")
            if (
                not isinstance(draft_id, str)
                or not draft_id.startswith("draft:")
                or len(draft_id) > 256
            ):
                raise ProtocolError("draft consumption requires a bounded 'draft:' id")
            return
        if "draft_id" in payload:
            raise ProtocolError("draft consumption payload must contain only 'draft_id'")
        cell = payload.get("cell")
        if not isinstance(cell, str) or not cell.startswith("cell."):
            raise ProtocolError(
                "cell payload must name a 'cell.*' capability or contain only 'draft_id'"
            )
        return
    if "lease" not in envelope:
        raise ProtocolError(f"consume mode {mode!r} requires 'lease'")
    validate_lease_dict(envelope["lease"])
    expected = envelope.get("expected")
    if mode == "verify":
        if not isinstance(expected, dict):
            raise ProtocolError("consume mode 'verify' requires 'expected'")
        for key in ("owner", "tool", "scope"):
            if not isinstance(expected.get(key), str):
                raise ProtocolError(f"verify expected field {key!r} must be a string")
        return
    if mode == "preflight":
        if not isinstance(expected, dict):
            raise ProtocolError("consume mode 'preflight' requires 'expected'")
        _validate_bound_expected(expected)
        return
    # mode == "consume": expected present → bound consume, absent → plain consume
    if expected is not None:
        _validate_bound_expected(expected)


def _validate_bound_expected(expected: dict[str, Any]) -> None:
    string_keys = (
        "product_id",
        "owner_key_hash",
        "session_id",
        "run_id",
        "tool_name",
        "args_schema",
        "resource_scope",
        "network_policy",
    )
    for key in string_keys:
        if not isinstance(expected.get(key), str):
            raise ProtocolError(f"expected field {key!r} must be a string")
    for key in ("fs_roots", "network_hosts"):
        value = expected.get(key)
        if not isinstance(value, (list, tuple)) or any(not isinstance(item, str) for item in value):
            raise ProtocolError(f"expected field {key!r} must be a list of strings")
    for key in ("max_bytes", "max_duration_ms"):
        value = expected.get(key)
        if not isinstance(value, int) or isinstance(value, bool) or not 0 <= value <= MAX_SEQ:
            raise ProtocolError(f"expected field {key!r} must be a u64 integer")
    single = expected.get("require_single_use", True)
    if not isinstance(single, bool):
        raise ProtocolError("expected require_single_use must be a boolean")


