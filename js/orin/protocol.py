    __slots__ = ("name", "kinds", "optional", "max_len", "lo", "hi")

    def __init__(
        self,
        name: str,
        *,
        kinds: tuple[type, ...],
        optional: bool = False,
        max_len: int = MAX_STRING_LENGTH,
        lo: int = 0,
        hi: int = MAX_SEQ,
    ) -> None:
        self.name = name
        self.kinds = kinds
        self.optional = optional
        self.max_len = max_len
        self.lo = lo
        self.hi = hi


